from datetime import datetime
from typing import Optional, Protocol

from dominio.modelos import (
    Dispositivo, Especie, LecturaGuardada, Planta, Puntaje, Usuario,
)


class EspecieRepositorioPuerto(Protocol):
    def obtener(self, nombre: str) -> Optional[Especie]: ...
    def listar(self) -> list[Especie]: ...


class UsuarioRepositorioPuerto(Protocol):
    def crear(self, correo: str, clave_hash: str) -> Usuario: ...
    def por_correo(self, correo: str) -> Optional[Usuario]: ...


class PlantaRepositorioPuerto(Protocol):
    def crear(self, usuario_id: int, nombre: str, especie: str) -> Planta: ...
    def obtener(self, planta_id: str) -> Optional[Planta]: ...
    def de_usuario(self, usuario_id: int) -> list[Planta]: ...


class DispositivoRepositorioPuerto(Protocol):
    def guardar(self, dispositivo: Dispositivo) -> None: ...
    def obtener(self, dispositivo_id: str) -> Optional[Dispositivo]: ...
    def de_planta(self, planta_id: str) -> Optional[Dispositivo]: ...


class HistorialPuerto(Protocol):
    def agregar(self, planta_id: str, lectura: LecturaGuardada) -> None: ...
    def recientes(self, planta_id: str, limite: int) -> list[LecturaGuardada]: ...


class PuntajeRepositorioPuerto(Protocol):
    def obtener(self, planta_id: str) -> Puntaje: ...
    def guardar(self, puntaje: Puntaje) -> None: ...


class HasheadorPuerto(Protocol):
    def hashear(self, clave: str) -> str: ...
    def coincide(self, clave: str, clave_hash: str) -> bool: ...


class EmisorTokenPuerto(Protocol):
    def para_usuario(self, usuario_id: int) -> str: ...
    def para_dispositivo(self, dispositivo_id: str, generacion: int) -> str: ...


class RelojPuerto(Protocol):
    def ahora(self) -> datetime: ...
